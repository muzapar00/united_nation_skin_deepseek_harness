/** Full CSS custom-property name for a palette key (the public token name). */
function tokenName(name) {
  if (/^(specific-|static-|radius-|shadow-|focus-|elevation-|font-)/.test(name)) return '--dsw-' + name
  return '--dsw-alias-' + name
}

/** Build the `{ token: { light, dark } }` override layer. */
function buildTokenOverrides() {
  var out = {}
  for (var name in LIGHT) {
    out[tokenName(name)] = { light: LIGHT[name], dark: DARK[name] !== undefined ? DARK[name] : LIGHT[name] }
  }
  return out
}

/** Same palette as CSS custom properties, so the body scope also carries it. */
function tokenCss() {
  var lines = []
  for (var name in LIGHT) {
    lines.push('  ' + tokenName(name) + ':' + LIGHT[name] + ' !important;')
  }
  return lines.join('\n')
}

function tokenCssDark() {
  var lines = []
  for (var name in DARK) {
    lines.push('  ' + tokenName(name) + ':' + DARK[name] + ' !important;')
  }
  return lines.join('\n')
}
